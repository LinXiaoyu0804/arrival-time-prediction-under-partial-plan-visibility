def freeze_protocol():
    path = OUT / "protocol.json"
    if path.exists():
        assert json.loads(path.read_text(encoding="utf8")) == PROTOCOL
    else:
        path.write_text(json.dumps(PROTOCOL, ensure_ascii=False, indent=2), encoding="utf8")
    amendment = {
        "date": "2026-09-13",
        "change": (
            "Assign every route to one batch using the Country, Week ID, and Day of Week recorded on "
            "its earliest executed stop (minimum IndexA)."
        ),
        "reason": (
            "A failed invariant check showed that 17 of 470 tuning routes crossed a calendar-day or "
            "week boundary. Grouping task rows directly would split a route across dispatch batches "
            "and create more than one minimum query for that route."
        ),
        "result_inspected_before_change": False,
    }
    (OUT / "protocol_amendment.json").write_text(
        json.dumps(amendment, ensure_ascii=False, indent=2), encoding="utf8"
    )
    shutil.copy2(__file__, OUT / "code" / Path(__file__).name)


def add_fields(q, threshold):
    q = qb.add_tie(q)
    q["route_size"] = q.groupby("Route ID")["Route ID"].transform("size")
    q["clean_gain"] = q.base_error - q.proxy_error
    q["responds"] = q.entropy.le(threshold)
    q["response_gain"] = q.clean_gain * q.responds
    route_start = (
        q.sort_values(["Route ID", "IndexA", "_tie"])
        .groupby("Route ID", as_index=False)
        .first()[["Route ID", "Country", "Week ID", "Day of Week"]]
        .rename(
            columns={
                "Country": "_batch_country",
                "Week ID": "_batch_week",
                "Day of Week": "_batch_day",
            }
        )
        .set_index("Route ID")
    )
    for column in BATCH_COLUMNS:
        q[column] = q["Route ID"].map(route_start[column])
    assert q.groupby("Route ID")[BATCH_COLUMNS].nunique().to_numpy().max() == 1
    return q


def daily_batch_selection(q, priority, budget, cap=10, minimum=1):
    selected = np.zeros(len(q), dtype=bool)
    priority = np.asarray(priority, dtype=float)
    for _, ids_frame in q.reset_index().groupby(BATCH_COLUMNS, sort=True):
        ids = ids_frame["index"].to_numpy()
        sub = q.loc[ids].reset_index(drop=True)
        if budget == 0:
            continue
        target = int(np.minimum(int(budget), sub.groupby("Route ID").size()).sum())
        cap_value = int(sub.route_size.max()) if cap == "unlimited" else int(cap)
        if target > int(np.minimum(sub.groupby("Route ID").size().to_numpy(), cap_value).sum()):
            raise ValueError("Infeasible cap for matched batch capacity")
        local = ra.global_capacity_selection(sub, priority[ids], target, cap=cap_value)
        if minimum:
            # Re-run with a guaranteed within-route first allocation.
            local = constrained_batch_selection(sub, priority[ids], target, cap_value, minimum)
        selected[ids] = local
    return selected


def constrained_batch_selection(q, priority, total_attempts, cap, minimum):
    selected = np.zeros(len(q), dtype=bool)
    route_codes, route_labels = pd.factorize(q["Route ID"], sort=True)
    counts = np.zeros(len(route_labels), dtype=np.int32)
    values = np.asarray(priority, dtype=float)
    for code in range(len(route_labels)):
        ids = np.flatnonzero(route_codes == code)
        order = ids[np.lexsort((q._tie.to_numpy()[ids], -values[ids]))]
        take = min(minimum, len(order))
        selected[order[:take]] = True
        counts[code] = take
    used = int(selected.sum())
    if used > total_attempts:
        raise ValueError("Minimum coverage exceeds capacity")
    if used == total_attempts:
        return selected
    order = np.lexsort((q._tie.to_numpy(), -values))
    for i in order:
        if selected[i]:
            continue
        code = route_codes[i]
        if counts[code] >= cap:
            continue
        selected[i] = True
        counts[code] += 1
        used += 1
        if used == total_attempts:
            break
    assert used == total_attempts
    return selected


def window_route_rows(q, selected, origin, k, method, budget, allocation, condition, split):
    route = ra.make_route_rows(q, selected, origin, k, method, budget, allocation, condition)
    route["split"] = split
    return route


def summarize(route_rows, extra_keys=None):
    keys = ["split", "condition", "k", "method", "budget", "allocation"]
    if extra_keys:
        keys += extra_keys
    rows = []
    for key, group in route_rows.groupby(keys):
        attempts = group.attempts.to_numpy()
        rows.append(
            {
                **dict(zip(keys, key)),
                "routes": group["Route ID"].nunique(),
                "drivers": group.driver.nunique(),
                "baseline_mae": group.baseline_mae.mean(),
                "mae": group.mae.mean(),
                "system_gain": group.system_gain.mean(),
                "queries_per_route": attempts.mean(),
                "delivery_equal_gain": group.selected_gain_sum.sum() / group.route_size.sum(),
                "response_rate": group.responses.sum() / max(attempts.sum(), 1),
                "zero_query_routes_percent": 100 * np.mean(attempts == 0),
                "attempts_median": np.median(attempts),
                "attempts_p90": np.quantile(attempts, 0.9),
                "attempt_gini": ra.gini(attempts),
            }
        )
    return pd.DataFrame(rows)


def compare_to_uniform(route_rows):
    rows = []
    keys = ["split", "condition", "k", "method", "budget"]
    for key, group in route_rows.groupby(keys):
        uniform = group[group.allocation.eq("uniform_route")]
        for allocation in ["daily_raw_cap10_min1", "daily_objective_cap10_min1"]:
            alternative = group[group.allocation.eq(allocation)]
            stats = ra.driver_bootstrap_difference(alternative, uniform)
            rows.append({**dict(zip(keys, key)), "allocation": allocation, **stats})
    return pd.DataFrame(rows)


def prepare_windows():
    raw = qb.load_raw()
    weeks = raw.groupby("Route ID")['Week ID'].agg(["min", "max"])
    windows = {}
    for origin in [13, 19, 25]:
        calibration = raw[
            raw["Route ID"].isin(weeks.index[(weeks["min"] >= origin - 6) & (weeks["max"] < origin)])
        ].copy()
        budget_tune = calibration[
            calibration["Route ID"].isin(weeks.index[weeks["min"] >= origin - 2])
        ].copy()
        for k in [3, 5]:
            name = f"w{origin}_k{k}"
            eta_model = joblib.load(SCENARIO / f"models/{name}.joblib")
            temporary = joblib.load(BUDGET_OUT / f"models/{name}_temporary_scores.joblib")
            tune = qb.answer_losses(budget_tune, eta_model, k)
            freeze = json.loads((SCENARIO / f"{name}_freeze.json").read_text(encoding="utf8"))
            threshold = freeze["refusal_thresholds"]["0.5"]
            tune = add_fields(tune, threshold)
            tune["DG_score"] = temporary["DG"].predict(tune[temporary["features"]])
            tune["ER_score"] = temporary["ER"].predict(tune[temporary["features"]])

            evaluation = add_fields(ra.load_window(origin, k), threshold)
            windows[(origin, k)] = {"tune": tune.reset_index(drop=True), "evaluation": evaluation.reset_index(drop=True)}
            tune.to_parquet(OUT / f"cache/w{origin}_k{k}_budget_tune.parquet", index=False)
    return windows


def fixed_grid(windows):
    rows = []
    selections = []
    for (origin, k), parts in windows.items():
        for split in ["budget_tuning", "evaluation"]:
            q = parts["tune" if split == "budget_tuning" else "evaluation"]
            for method, score_column in METHODS.items():
                for budget in BUDGETS:
                    uniform = qb.deterministic_selection(q, score_column, budget)
                    raw = daily_batch_selection(q, q[score_column], budget, cap=10, minimum=1)
                    objective = daily_batch_selection(q, q[score_column] / q.route_size, budget, cap=10, minimum=1)
                    assert uniform.sum() == raw.sum() == objective.sum(), (
                        origin,
                        k,
                        split,
                        method,
                        budget,
                        int(uniform.sum()),
                        int(raw.sum()),
                        int(objective.sum()),
                    )
                    for condition in CONDITIONS:
                        for allocation, selected in {
                            "uniform_route": uniform,
                            "daily_raw_cap10_min1": raw,
                            "daily_objective_cap10_min1": objective,
                        }.items():
                            rows.append(
                                window_route_rows(
                                    q, selected, origin, k, method, budget, allocation, condition, split
                                )
                            )
                            if split == "evaluation" and k == 5:
                                selections.append(
                                    pd.DataFrame(
                                        {
                                            "_rowkey": q._rowkey,
                                            "window": origin,
                                            "method": method,
                                            "budget": str(budget),
                                            "allocation": allocation,
                                            "selected": selected,
                                        }
                                    )
                                )
        print(time.strftime("%H:%M:%S"), f"fixed w{origin}_k{k}", flush=True)
    route_rows = pd.concat(rows, ignore_index=True)
    route_rows.to_parquet(OUT / "tables/fixed_grid_route_results.parquet", index=False)
    pd.concat(selections, ignore_index=True).to_parquet(OUT / "tables/k5_evaluation_selections.parquet", index=False)
    summarize(route_rows).to_csv(OUT / "tables/fixed_grid_summary.csv", index=False)
    compare_to_uniform(route_rows[route_rows.split.eq("evaluation")]).to_csv(
        OUT / "tables/fixed_grid_driver_cluster_comparisons.csv", index=False
    )
    return route_rows


def cap_candidates(budget):
    return [cap for cap in CAPS if cap == "unlimited" or int(cap) >= int(budget)]


def select_config(table, rule):
    table = table.copy()
    table["cap_order"] = table.cap.map(lambda x: 999 if x == "unlimited" else int(x))
    table["budget_order"] = table.budget.astype(int)
    best_gain = table.system_gain.max()
    if rule == "minimum_mae":
        eligible = table[table.system_gain.eq(best_gain)]
    else:
        eligible = table[table.system_gain.ge(0.9 * best_gain)]
    return eligible.sort_values(["budget_order", "cap_order"]).iloc[0], best_gain


def past_only_selection(windows, fixed_rows):
    old_choices = pd.read_csv(BUDGET_OUT / "tables/past_only_budget_choices.csv")
    conditional_choices = []
    conditional_routes = []
    joint_choices = []
    joint_routes = []

    for origin in [13, 19, 25]:
        for k in [3, 5]:
            tune = windows[(origin, k)]["tune"]
            evaluation = windows[(origin, k)]["evaluation"]
            for condition in CONDITIONS:
                gain_column = CONDITIONS[condition]
                for method, score_column in METHODS.items():
                    # Joint budget-cap selection on the tuning period.
                    candidate_rows = []
                    for budget in BUDGETS:
                        for cap in cap_candidates(budget):
                            selected = daily_batch_selection(
                                tune, tune[score_column] / tune.route_size, budget, cap=cap, minimum=1
                            )
                            route = window_route_rows(
                                tune, selected, origin, k, method, budget, "candidate", condition, "budget_tuning"
                            )
                            candidate_rows.append(
                                {"budget": str(budget), "cap": str(cap), "system_gain": route.system_gain.mean()}
                            )
                    candidate_table = pd.DataFrame(candidate_rows)
                    for rule in ["minimum_mae", "knee90"]:
                        chosen, best_gain = select_config(candidate_table, rule)
                        selected = daily_batch_selection(
                            evaluation,
                            evaluation[score_column] / evaluation.route_size,
                            int(chosen.budget),
                            cap=chosen.cap,
                            minimum=1,
                        )
                        route = window_route_rows(
                            evaluation,
                            selected,
                            origin,
                            k,
                            method,
                            chosen.budget,
                            "joint_past_only",
                            condition,
                            "evaluation",
                        )
                        route["rule"] = rule
                        route["chosen_cap"] = chosen.cap
                        joint_routes.append(route)
                        joint_choices.append(
                            {
                                "window": origin,
                                "k": k,
                                "condition": condition,
                                "method": method,
                                "rule": rule,
                                "chosen_budget": chosen.budget,
                                "chosen_cap": chosen.cap,
                                "tuning_gain": chosen.system_gain,
                                "best_tuning_gain": best_gain,
                                "evaluation_gain": route.system_gain.mean(),
                                "evaluation_mae": route.mae.mean(),
                                "evaluation_queries_per_route": route.attempts.mean(),
                            }
                        )

                    # Cap selection conditional on the already frozen uniform-route budget.
                    for old in old_choices[
                        old_choices.window.eq(origin)
                        & old_choices.k.eq(k)
                        & old_choices.condition.eq(condition)
                        & old_choices.method.eq(method)
                    ].itertuples(index=False):
                        budget = int(old.chosen_budget)
                        cap_rows = candidate_table[candidate_table.budget.eq(str(budget))]
                        chosen, best_gain = select_config(cap_rows.assign(budget=str(budget)), "minimum_mae")
                        selected = daily_batch_selection(
                            evaluation,
                            evaluation[score_column] / evaluation.route_size,
                            budget,
                            cap=chosen.cap,
                            minimum=1,
                        )
                        route = window_route_rows(
                            evaluation,
                            selected,
                            origin,
                            k,
                            method,
                            budget,
                            "conditional_cap_past_only",
                            condition,
                            "evaluation",
                        )
                        route["rule"] = old.rule
                        route["chosen_cap"] = chosen.cap
                        conditional_routes.append(route)
                        conditional_choices.append(
                            {
                                "window": origin,
                                "k": k,
                                "condition": condition,
                                "method": method,
                                "rule": old.rule,
                                "chosen_budget": budget,
                                "chosen_cap": chosen.cap,
                                "tuning_gain": chosen.system_gain,
                                "best_tuning_gain": best_gain,
                                "evaluation_gain": route.system_gain.mean(),
                                "evaluation_mae": route.mae.mean(),
                                "evaluation_queries_per_route": route.attempts.mean(),
                            }
                        )

    conditional_routes = pd.concat(conditional_routes, ignore_index=True)
    joint_routes = pd.concat(joint_routes, ignore_index=True)
    conditional_routes.to_parquet(OUT / "tables/conditional_cap_route_results.parquet", index=False)
    joint_routes.to_parquet(OUT / "tables/joint_past_only_route_results.parquet", index=False)
    pd.DataFrame(conditional_choices).to_csv(OUT / "tables/conditional_cap_choices.csv", index=False)
    pd.DataFrame(joint_choices).to_csv(OUT / "tables/joint_past_only_choices.csv", index=False)

    # Summaries and paired comparisons against the corresponding old uniform choices.
    comparisons = []
    for label, routes in [
        ("conditional_cap", conditional_routes),
        ("joint", joint_routes),
    ]:
        for key, group in routes.groupby(["condition", "k", "method", "rule"]):
            condition, k, method, rule = key
            if label == "conditional_cap":
                old = old_choices[
                    old_choices.condition.eq(condition)
                    & old_choices.k.eq(k)
                    & old_choices.method.eq(method)
                    & old_choices.rule.eq(rule)
                ]
                uniform_parts = []
                for choice in old.itertuples(index=False):
                    uniform_parts.append(
                        fixed_rows[
                            fixed_rows.window.eq(choice.window)
                            & fixed_rows.k.eq(k)
                            & fixed_rows.condition.eq(condition)
                            & fixed_rows.method.eq(method)
                            & fixed_rows.budget.eq(str(choice.chosen_budget))
                            & fixed_rows.allocation.eq("uniform_route")
                            & fixed_rows.split.eq("evaluation")
                        ]
                    )
                uniform = pd.concat(uniform_parts, ignore_index=True)
                stats = ra.driver_bootstrap_difference(group, uniform)
                uniform_gain = uniform.system_gain.mean()
                uniform_mae = uniform.mae.mean()
            else:
                # Joint choice can change query counts, so compare with no-query baseline rather than
                # claiming a same-workload contrast.
                stats = ra.driver_bootstrap_difference(
                    group,
                    group.assign(system_gain=0.0),
                )
                uniform_gain = np.nan
                uniform_mae = np.nan
            comparisons.append(
                {
                    "selection": label,
                    "condition": condition,
                    "k": k,
                    "method": method,
                    "rule": rule,
                    "baseline_mae": group.baseline_mae.mean(),
                    "comparison_mae": uniform_mae,
                    "selected_mae": group.mae.mean(),
                    "comparison_gain": uniform_gain,
                    "selected_gain": group.system_gain.mean(),
                    "queries_per_route": group.attempts.mean(),
                    **stats,
                }
            )
    pd.DataFrame(comparisons).to_csv(OUT / "tables/past_only_policy_comparisons.csv", index=False)


def main():
    freeze_protocol()
    windows = prepare_windows()
    fixed = fixed_grid(windows)
    past_only_selection(windows, fixed)
    (OUT / "completion.json").write_text(
        json.dumps(
            {
                "status": "complete",
                "time": time.strftime("%Y-%m-%d %H:%M:%S"),
                "batch_columns": SOURCE_BATCH_COLUMNS,
                "route_batch_anchor": "minimum IndexA",
                "windows": 3,
                "answer_categories": [3, 5],
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf8",
    )


if __name__ == "__main__":
    main()
